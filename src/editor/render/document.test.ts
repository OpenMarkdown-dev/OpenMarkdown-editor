import { describe, expect, it } from "vitest";
import { buildHtmlDocument, mathLoaded } from "./document";
import { mermaidMarkup } from "../markup";

const md = [
  "# Plan",
  "",
  "![local|40](a.png) ![remote](https://x.dev/r.png) ![missing](b.png)",
  "",
  "```mermaid",
  "graph LR",
  "```",
  "",
  "$E = mc^2$",
  "",
].join("\n");

describe("buildHtmlDocument", () => {
  const page = buildHtmlDocument(md, {
    title: "Plan <draft>",
    lang: "zh",
    images: new Map([["a.png", "data:image/png;base64,AAAA"]]),
    diagrams: new Map([["graph LR", mermaidMarkup('<svg id="om-mermaid-1" viewBox="0 0 1 1"></svg>')]]),
    math: () => null,
  });

  it("is a whole page with its title escaped and the stylesheet inline", () => {
    expect(page.startsWith("<!doctype html>\n<html lang=\"zh\">")).toBe(true);
    expect(page).toContain("<title>Plan &lt;draft&gt;</title>");
    expect(page).toMatch(/<style>\n\/\* Generated by OpenMarkdown/);
    expect(page).toContain('<body class="om-doc">');
  });

  it("embeds given local images, keeps remote ones, keeps an unread local src as written", () => {
    expect(page).toContain('<img src="data:image/png;base64,AAAA" alt="local" width="40">');
    expect(page).toContain('<img src="https://x.dev/r.png" alt="remote">');
    expect(page).toContain('<img src="b.png" alt="missing">');
  });

  it("places the drawn diagram", () => {
    expect(page).toContain('<figure class="om-mermaid"><svg id="om-mermaid-1"');
  });

  it("is self-contained: no script, no external stylesheet, no handler", () => {
    expect(page).not.toMatch(/<script|<link\b|@import|\son[a-z]+=|javascript:/i);
  });
});

describe("mathLoaded + the real converter", () => {
  it("renders formulas as MathML once loaded", async () => {
    await mathLoaded();
    const page = buildHtmlDocument("$x^2$\n", { title: "m" });
    expect(page).toMatch(/<span class="om-math"><math/);
  });
});
